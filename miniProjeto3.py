# Mini-Projeto 3: O Sorteador de Nomes
# Programa que dá “Olá” para uma lista de convidados

convidados = ["Ana", "Bruno", "Carla", "Daniel"]

print("--- Iniciando a Festa ---")

# O loop 'for' vai passar por cada nome na lista
for nome in convidados:
    print(f"Olá, {nome}! Seja bem-vindo(a)!")

print("--- Todos foram convidados! ---")

#Terminal: python miniProjeto3.py